# Pertemuan 3 - Jawaban soal 3
# ------------------------------------------------------------
# Soal:
#   Minta tiga nilai ujian (desimal) dan tampilkan rata-ratanya dengan 2 angka
#   di belakang koma.
# ------------------------------------------------------------

n1 = float(input("Nilai 1: "))
n2 = float(input("Nilai 2: "))
n3 = float(input("Nilai 3: "))
rata = (n1 + n2 + n3) / 3
print(f"Rata-rata: {rata:.2f}")

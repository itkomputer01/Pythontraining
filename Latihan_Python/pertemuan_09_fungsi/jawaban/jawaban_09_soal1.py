#   Buat fungsi luas_lingkaran(r) yang mengembalikan luas lingkaran (gunakan
#   3.14159) dan panggil dengan r = 7.
# ------------------------------------------------------------

def luas_lingkaran(r):
    return 3.14159 * r * r

print(luas_lingkaran(7))


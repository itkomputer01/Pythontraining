# Soal:
#   Konversikan suhu 37 derajat Celsius ke Fahrenheit dan Kelvin. Rumus: F = C ×
#   9/5 + 32, K = C + 273,15.
# ------------------------------------------------------------

celsius = 37
fahrenheit = celsius * 9 / 5 + 32
kelvin = celsius + 273.15
print(fahrenheit, kelvin)

# Contoh output:
#   98.6 310.15

